#!/bin/bash
# GrasaDroid: Phase A del stack GPU para iOS — ANGLE + epoxy + virglrenderer,
# y QEMU reconfigurado con --enable-opengl --enable-virglrenderer.
#
# La ruta viable es virgl (GL) -> epoxy -> ANGLE -> Metal (Venus queda fuera:
# es solo-Vulkan y Android es mayormente GLES). Basado en los scripts de Husk
# (build_gpu_ios.sh / build_angle_ios.sh), que probaron que este stack compila
# para iOS. Nadie ha renderizado un frame de un guest por virgl en iOS todavía:
# el puente de display (dpy_gl_scanout_texture -> CAMetalLayer) es fase C.
#
# Este script es autocontenido: si el sysroot no trae las dependencias base,
# primero corre scripts/build-qemu-ios.sh para construirlas.
# (2026-10-12: fix aplicado al base — apply_patch separaba mal un `local` con set -u.)
set -uo pipefail

GRASA_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SRC="$GRASA_ROOT/third_party/build"
GPU="$GRASA_ROOT/third_party/gpu"
PREFIX="$GRASA_ROOT/third_party/ios-arm64/sysroot"
LIBDIR="$GRASA_ROOT/third_party/ios-arm64/lib"
GPULIBDIR="$GRASA_ROOT/third_party/ios-arm64/lib-gpu"
PATCHDIR="$GRASA_ROOT/third_party/patches"
LOGS="$GRASA_ROOT/third_party/logs"
mkdir -p "$SRC" "$GPU" "$PREFIX" "$LIBDIR" "$GPULIBDIR" "$PATCHDIR" "$LOGS"

ARCH=arm64
SDK=iphoneos
SDKMINVER="${SDKMINVER:-15.5}"
NCPU="$(sysctl -n hw.ncpu)"

EPOXY_REPO="https://github.com/utmapp/libepoxy.git"
EPOXY_COMMIT="bf98587477fe68d07b93319ece7b40a7d0e2eabe"
VIRGL_REPO="https://github.com/utmapp/virglrenderer.git"
VIRGL_COMMIT="482f9d8b8c2d2288efa10a027116216909d2c226"
EPOXY_PATCH_URL="https://raw.githubusercontent.com/leviidev/husk/HEAD/patches/husk-epoxy-ios-egl-path.patch"

banner() { printf '\n\033[0;32m=== %s ===\033[0m\n' "$*"; }
fail()   { printf '\033[0;31m[FAIL] %s\033[0m\n' "$1"; [ -n "$2" ] && [ -f "$2" ] && tail -25 "$2"; exit 1; }

# ---------------------------------------------------------------- toolchain
SDKROOT="$(xcrun --sdk $SDK --show-sdk-path)"
CFLAGS_TARGET="-target $ARCH-apple-ios$SDKMINVER"

export CC="$(xcrun --sdk $SDK --find clang) $CFLAGS_TARGET"
export CXX="$(xcrun --sdk $SDK --find clang++) $CFLAGS_TARGET"
export AR="$(xcrun --sdk $SDK --find ar)"
export NM="$(xcrun --sdk $SDK --find nm)"
export RANLIB="$(xcrun --sdk $SDK --find ranlib)"
export STRIP="$(xcrun --sdk $SDK --find strip)"
export LD="$(xcrun --sdk $SDK --find ld)"

export CFLAGS="-arch $ARCH -isysroot $SDKROOT -I$PREFIX/include $CFLAGS_TARGET -O2"
export CXXFLAGS="$CFLAGS"
export CPPFLAGS="-arch $ARCH -isysroot $SDKROOT -I$PREFIX/include $CFLAGS_TARGET"
export LDFLAGS="-arch $ARCH -isysroot $SDKROOT -L$PREFIX/lib $CFLAGS_TARGET"

# pkg-config solo ve nuestro sysroot.
export PKG_CONFIG_LIBDIR="$PREFIX/lib/pkgconfig:$PREFIX/share/pkgconfig"
unset PKG_CONFIG_PATH || true

meson_quote() { echo "'$(echo $* | sed "s/ /','/g")'"; }

gen_cross() {
    local cross="$1" system="$2"
    cat > "$cross" <<EOF
# Generated by GrasaDroid build-qemu-gpu-ios.sh - do not edit
[properties]
needs_exe_wrapper = true
[built-in options]
c_args = [$(meson_quote $CFLAGS)]
cpp_args = [$(meson_quote $CXXFLAGS)]
c_link_args = [$(meson_quote $LDFLAGS)]
cpp_link_args = [$(meson_quote $LDFLAGS)]
[binaries]
c = [$(meson_quote $CC)]
cpp = [$(meson_quote $CXX)]
objc = [$(meson_quote $CC)]
ar = ['$AR']
nm = ['$NM']
ranlib = ['$RANLIB']
strip = ['$STRIP', '-x']
pkg-config = ['$(command -v pkg-config)']
pkgconfig = ['$(command -v pkg-config)']
python = ['$(command -v python3)']
[host_machine]
system = '$system'
EOF
    if [ "$system" = "darwin" ]; then
        echo "kernel = 'xnu'" >> "$cross"
        echo "subsystem = 'ios'" >> "$cross"
    fi
    cat >> "$cross" <<EOF
cpu_family = 'aarch64'
cpu = 'aarch64'
endian = 'little'
EOF
}

CROSS_IOS="$GRASA_ROOT/third_party/ios-arm64/cross-ios.meson"
CROSS_DARWIN="$GRASA_ROOT/third_party/ios-arm64/cross-darwin.meson"
gen_cross "$CROSS_IOS" ios
gen_cross "$CROSS_DARWIN" darwin

# ---------------------------------------------------------------- base deps
if [ ! -f "$PREFIX/lib/pkgconfig/glib-2.0.pc" ]; then
    banner "dependencias base no encontradas: construyendo base primero"
    bash "$GRASA_ROOT/scripts/build-qemu-ios.sh" || { echo "[FAIL] base build"; exit 1; }
else
    echo "[skip] dependencias base ya en sysroot"
fi

# ---------------------------------------------------------------- ANGLE
# EGL + GLES sobre Metal, desde el árbol ANGLE de WebKit (evita depot_tools/gn).
if [ ! -f "$PREFIX/lib/libANGLE-shared.dylib" ]; then
    banner "building ANGLE for iOS arm64"
    WK="$GPU/webkit"
    ALOG="$LOGS/angle.log"
    # Pin a WebKit previo al refactor de ResourceMap (ANGLE 2025-11-28):
    # WebKit-main trae un static_assert(kNeedsLock) inconsistente que rompe
    # la compilación con cualquier clang. No perseguir main.
    # (SHA completo: git fetch por SHA corto no resuelve en GitHub)
    WEBKIT_PIN="ed8bfa2b0f4d82867ddd51764ad66d5ddf4adb52"
    if [ ! -d "$WK" ]; then
        echo "[fetch] WebKit @ $WEBKIT_PIN"
        git clone --depth 1 --filter=blob:none --sparse \
            https://github.com/WebKit/WebKit.git "$WK" > "$ALOG" 2>&1 \
            || fail "webkit clone" "$ALOG"
        ( cd "$WK" \
          && git sparse-checkout set Source/ThirdParty/ANGLE Configurations Tools/Scripts Tools/ccache \
          && git fetch --depth 1 origin "$WEBKIT_PIN" \
          && git checkout -q "$WEBKIT_PIN" ) >> "$ALOG" 2>&1 \
            || fail "webkit pin" "$ALOG"
    fi

    cd "$WK/Source/ThirdParty/ANGLE"
    ALIASES="$GPU/angle-aliases.txt"

    angle_build() {
        local ldflags=()
        if [ -n "${1:-}" ]; then
            ldflags=("OTHER_LDFLAGS=\$(inherited) -Wl,-alias_list,$1")
        fi
        env -i PATH="$PATH" HOME="$HOME" xcodebuild archive \
            -archivePath "ANGLE" -scheme "ANGLE" \
            -sdk iphoneos -arch arm64 -configuration Release \
            WEBCORE_LIBRARY_DIR="/usr/local/lib" NORMAL_UMBRELLA_FRAMEWORKS_DIR="" \
            CODE_SIGNING_ALLOWED=NO CODE_SIGNING_REQUIRED=NO \
            WK_AVAILABILITY_OVERLAY_FLAGS="" WK_AVAILABILITY_OVERLAY_SWIFT_FLAGS="" \
            IPHONEOS_DEPLOYMENT_TARGET="15.5" \
            OTHER_CFLAGS='$(inherited) -Wno-unguarded-availability-new -Wno-thread-safety' \
            OTHER_CPLUSPLUSFLAGS='$(inherited) -Wno-unguarded-availability-new -Wno-thread-safety' \
            ${ldflags[@]+"${ldflags[@]}"} \
            > "$ALOG" 2>&1 \
          || { echo "ANGLE build failed; last errors:" >&2
               grep -a "error:\|^ld: " "$ALOG" | head -10 >&2; exit 1; }
    }

    echo "==> ANGLE pass 1"
    angle_build ""
    echo "==> generating EGL symbol aliases"
    nm -g "ANGLE.xcarchive/Products/usr/local/lib/libANGLE-shared.dylib" \
      | awk '$2=="T"{print $3}' | grep -E '^_EGL_' \
      | awk '{o=$1; a=$1; sub(/^_EGL_/,"_egl",a); print o, a}' > "$ALIASES"
    echo "    $(wc -l < "$ALIASES") aliases"
    echo "==> ANGLE pass 2 (relink with standard EGL names)"
    angle_build "$ALIASES"

    DYLIB="ANGLE.xcarchive/Products/usr/local/lib/libANGLE-shared.dylib"
    [ -f "$DYLIB" ] || { echo "[FAIL] no ANGLE dylib at $DYLIB"; exit 1; }
    install -d "$PREFIX/lib" "$PREFIX/include"
    cp "$DYLIB" "$PREFIX/lib/"
    rsync -a "include/" "$PREFIX/include/"
    install_name_tool -id "@rpath/libANGLE-shared.dylib" "$PREFIX/lib/libANGLE-shared.dylib"
    echo "==> ANGLE staged: $(ls -lh "$PREFIX/lib/libANGLE-shared.dylib" | awk '{print $5}')"
    echo "==> standard EGL entry points: $(nm -g "$PREFIX/lib/libANGLE-shared.dylib" | grep -c ' T _egl')"
    cd "$GRASA_ROOT"
else
    echo "[skip] ANGLE ya en sysroot"
fi

# ---------------------------------------------------------------- epoxy
if [ ! -f "$PREFIX/lib/libepoxy.a" ]; then
    banner "building libepoxy for iOS"
    [ -d "$GPU/epoxy" ] || git clone -q "$EPOXY_REPO" "$GPU/epoxy"
    ( cd "$GPU/epoxy" && git checkout -q "$EPOXY_COMMIT" )
    [ -f "$PATCHDIR/husk-epoxy-ios-egl-path.patch" ] || \
        curl -sSL --retry 3 -o "$PATCHDIR/husk-epoxy-ios-egl-path.patch" "$EPOXY_PATCH_URL"
    ( cd "$GPU/epoxy"
      git checkout -q -- src/dispatch_common.c 2>/dev/null || true
      patch -p1 --silent < "$PATCHDIR/husk-epoxy-ios-egl-path.patch" || true
      rm -rf _grasadroid_build
      meson setup _grasadroid_build --cross-file "$CROSS_IOS" \
          --prefix="$PREFIX" --default-library=static \
          -Dtests=false -Dglx=no -Degl=yes -Dx11=false
      ninja -C _grasadroid_build install ) > "$LOGS/epoxy.log" 2>&1 \
      || fail epoxy "$LOGS/epoxy.log"
    echo "    $(ls -lh "$PREFIX/lib/libepoxy.a" | awk '{print $5}')"
else
    echo "[skip] libepoxy ya en sysroot"
fi

# ---------------------------------------------------------------- virglrenderer
if [ ! -f "$PREFIX/lib/libvirglrenderer.a" ]; then
    banner "building virglrenderer for iOS (render server: thread mode)"
    # GrasaDroid: clone fresco de virglrenderer cada vez para evitar
    # contaminacion del "codigo fantasma" is_angle.
    rm -rf "$GPU/virgl"
    git clone -q "$VIRGL_REPO" "$GPU/virgl"
    ( cd "$GPU/virgl" && git checkout -q "$VIRGL_COMMIT" )
    # El archivo vrend_renderer.c aparece con codigo is_angle corrupto en el
    # runner aunque el commit no lo tiene. Lo descargamos directo desde GitHub
    # para garantizar la version pristina.
    ( cd "$GPU/virgl" && curl -sSL "https://raw.githubusercontent.com/utmapp/virglrenderer/$VIRGL_COMMIT/src/vrend/vrend_renderer.c" -o src/vrend/vrend_renderer.c && echo "[fix] vrend_renderer.c descargado desde GitHub raw" )
    ( cd "$GPU/virgl" && grep -q "is_angle" src/vrend/vrend_renderer.c && echo "[WARN] is_angle presente despues de descarga!" || echo "[fix] vrend_renderer.c limpio, sin is_angle" )
    # GrasaDroid: el winsys Metal de UTM es macOS-only; en iOS usamos EGL via ANGLE.
    # Sin esto, su meson.build ejecuta add_languages('objc') y compila vrend_metal.m
    # (causa raíz del fallo de GPU #6: meson pedía compilador objc aunque el cross
    # file ya lo tenía, y luego intentaba compilar código macOS para iOS).
    ( cd "$GPU/virgl" && python3 <<'PYEOF'
import re
p = "meson.build"
s = open(p).read()
s2, n = re.subn(r"(?m)^metal_dep = dependency\('appleframeworks'.*$",
                "metal_dep = not_found # GrasaDroid: winsys Metal desactivado en iOS (EGL via ANGLE)",
                s)
assert n == 1, "linea metal_dep no encontrada en meson.build"
open(p, "w").write(s2)
print("[patch] metal_dep -> not_found (winsys Metal desactivado)")
PYEOF
    )
    ( cd "$GPU/virgl" && python3 <<'PYEOF'
import re
p = "meson.build"
s = open(p).read()
s2, n = re.subn(r"(?m)^metal_dep = dependency\('appleframeworks'.*$",
                "metal_dep = not_found # GrasaDroid: winsys Metal desactivado en iOS (EGL via ANGLE)",
                s)
assert n == 1, "linea metal_dep no encontrada en meson.build"
open(p, "w").write(s2)
print("[patch] metal_dep -> not_found (winsys Metal desactivado)")
PYEOF
    )
    ( cd "$GPU/virgl"
      echo "[debug] vrend_renderer.c 13010-13025:"
      sed -n '13010,13025p' src/vrend/vrend_renderer.c
      rm -rf _grasadroid_build
      meson setup _grasadroid_build --cross-file "$CROSS_DARWIN" \
          --prefix="$PREFIX" --default-library=static \
          -Dtests=false -Dcheck-gl-errors=false -Dvenus=false -Dvulkan-dload=false \
          -Drender-server-mode=thread
      ninja -C _grasadroid_build install ) > "$LOGS/virgl.log" 2>&1 \
      || { echo "[errores de compilación]"; grep -a -B2 -A8 ": error:" "$LOGS/virgl.log" | head -60; fail virglrenderer "$LOGS/virgl.log"; }
    echo "    $(ls -lh "$PREFIX/lib/libvirglrenderer.a" | awk '{print $5}')"
else
    echo "[skip] virglrenderer ya en sysroot"
fi

# ---------------------------------------------------------------- QEMU + GPU flags
banner "building QEMU with --enable-opengl --enable-virglrenderer"
QDIR="$SRC/qemu-10.0.12-utm"
[ -d "$QDIR" ] || { echo "[FAIL] falta fuente QEMU en $QDIR"; exit 1; }
rm -rf "$QDIR/_gpu_build"; mkdir -p "$QDIR/_gpu_build"
( cd "$QDIR/_gpu_build" \
  && ../configure \
        --prefix="$PREFIX" \
        --cross-prefix="" \
        --target-list=aarch64-softmmu \
        --enable-shared-lib \
        --with-coroutine=libucontext \
        --enable-slirp \
        --enable-opengl --enable-virglrenderer \
        --disable-cocoa --disable-sdl --disable-gtk --disable-coreaudio \
        --disable-vnc --disable-spice \
        --disable-curses --disable-curl --disable-libusb --disable-usb-redir \
        --disable-tpm --disable-docs --disable-guest-agent --disable-tools \
        --disable-hvf --disable-vde --disable-brlapi --disable-libssh \
        --disable-bzip2 --disable-snappy --disable-lzo --disable-gnutls \
        --disable-png --disable-vte --disable-zstd \
        --disable-nettle --disable-gcrypt --disable-auth-pam \
        --disable-install-blobs --disable-sparse --disable-debug-info \
        --extra-cflags="$CFLAGS" --extra-ldflags="$LDFLAGS" \
  && make -j"$NCPU" ) > "$LOGS/qemu-gpu.log" 2>&1 || fail "qemu-gpu" "$LOGS/qemu-gpu.log"

echo "==> verificando flags GPU en el configure:"
grep -a -i "virgl\|opengl" "$LOGS/qemu-gpu.log" | grep -i "support.*yes" | head -5 || true

DYLIB_SRC="$QDIR/_gpu_build/libqemu-aarch64-softmmu.dylib"
[ -f "$DYLIB_SRC" ] || { echo "[FAIL] dylib GPU no producido"; exit 1; }
cp "$DYLIB_SRC" "$GPULIBDIR/"
cp "$PREFIX/lib/libANGLE-shared.dylib" "$GPULIBDIR/"
echo "[stage] $GPULIBDIR/"
ls -lh "$GPULIBDIR/"

echo
echo "QEMU iOS GPU build OK"
