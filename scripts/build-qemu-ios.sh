#!/bin/bash
# GrasaDroid: cross-compila QEMU aarch64-softmmu + dependencias mínimas para arm64-apple-ios.
#
# El setup del toolchain sigue el de UTM (scripts/build_dependencies.sh), vía la
# versión mínima de Husk (scripts/build_ios.sh): el triple -target, la forma del
# cross-file de meson, needs_exe_wrapper y el aislamiento de PKG_CONFIG_LIBDIR
# son la parte difícil y probada. Solo se compilan las 5 librerías necesarias
# para aarch64-softmmu (sin spice/gstreamer/virgl/usb/tpm).
#
# Producto: third_party/ios-arm64/lib/libqemu-aarch64-softmmu.dylib
set -uo pipefail

GRASA_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SRC="$GRASA_ROOT/third_party/build"
PREFIX="$GRASA_ROOT/third_party/ios-arm64/sysroot"
LIBDIR="$GRASA_ROOT/third_party/ios-arm64/lib"
PATCHDIR="$GRASA_ROOT/third_party/patches"
LOGS="$GRASA_ROOT/third_party/logs"
mkdir -p "$SRC" "$PREFIX" "$LIBDIR" "$PATCHDIR" "$LOGS"

ARCH=arm64
SDK=iphoneos
SDKMINVER="${SDKMINVER:-15.5}"
NCPU="$(sysctl -n hw.ncpu)"

# ---------------------------------------------------------------- fuentes
QEMU_SRC="https://github.com/utmapp/qemu/releases/download/v10.0.12-utm/qemu-10.0.12-utm.tar.xz"
FFI_SRC="https://github.com/libffi/libffi/releases/download/v3.5.0/libffi-3.5.0.tar.gz"
GLIB_SRC="https://download.gnome.org/sources/glib/2.83/glib-2.83.0.tar.xz"
PIXMAN_SRC="https://www.cairographics.org/releases/pixman-0.38.0.tar.gz"
LIBUCONTEXT_REPO="https://github.com/utmapp/libucontext.git"
LIBUCONTEXT_COMMIT="9b1d8f01a6e99166f9808c79966abe10786de8b6"
SLIRP_SRC="https://github.com/utmapp/libslirp/releases/download/v4.9.1-release-mirror/libslirp-v4.9.1.tar.gz"

PATCH_BASE="https://raw.githubusercontent.com/leviidev/husk/HEAD/patches"

banner() { printf '\n\033[0;32m=== %s ===\033[0m\n' "$*"; }
fail()   { printf '\033[0;31m[FAIL] %s (see %s)\033[0m\n' "$1" "$2"; exit 1; }

# ---------------------------------------------------------------- toolchain
SDKROOT="$(xcrun --sdk $SDK --show-sdk-path)"
CFLAGS_TARGET="-target $ARCH-apple-ios$SDKMINVER"

export CC="$(xcrun --sdk $SDK --find clang) $CFLAGS_TARGET"
export CXX="$(xcrun --sdk $SDK --find clang++) $CFLAGS_TARGET"
export AR="$(xcrun --sdk $SDK --find ar)"
export NM="$(xcrun --sdk $SDK --find nm)"
export RANLIB="$(xcrun --sdk $SDK --find ranlib)"
export STRIP="$(xcrun --sdk $SDK --find strip)"
export LD="$(xcrun --sdk $SDK --find ld)"

export CFLAGS="-arch $ARCH -isysroot $SDKROOT -I$PREFIX/include $CFLAGS_TARGET -O2"
export CXXFLAGS="$CFLAGS"
export CPPFLAGS="-arch $ARCH -isysroot $SDKROOT -I$PREFIX/include $CFLAGS_TARGET"
export LDFLAGS="-arch $ARCH -isysroot $SDKROOT -L$PREFIX/lib $CFLAGS_TARGET"

# pkg-config solo ve nuestro sysroot: que nunca se cuelen libs de Homebrew del host.
export PKG_CONFIG_LIBDIR="$PREFIX/lib/pkgconfig:$PREFIX/share/pkgconfig"
unset PKG_CONFIG_PATH || true

meson_quote() { echo "'$(echo $* | sed "s/ /','/g")'"; }

gen_cross() {
    local cross="$1" system="$2"
    cat > "$cross" <<EOF
# Generated by GrasaDroid build-qemu-ios.sh - do not edit
[properties]
needs_exe_wrapper = true
[built-in options]
c_args = [$(meson_quote $CFLAGS)]
cpp_args = [$(meson_quote $CXXFLAGS)]
c_link_args = [$(meson_quote $LDFLAGS)]
cpp_link_args = [$(meson_quote $LDFLAGS)]
[binaries]
c = [$(meson_quote $CC)]
cpp = [$(meson_quote $CXX)]
objc = [$(meson_quote $CC)]
ar = ['$AR']
nm = ['$NM']
ranlib = ['$RANLIB']
strip = ['$STRIP', '-x']
pkg-config = ['$(command -v pkg-config)']
pkgconfig = ['$(command -v pkg-config)']
python = ['$(command -v python3)']
[host_machine]
system = '$system'
EOF
    if [ "$system" = "darwin" ]; then
        echo "kernel = 'xnu'" >> "$cross"
        echo "subsystem = 'ios'" >> "$cross"
    fi
    cat >> "$cross" <<EOF
cpu_family = 'aarch64'
cpu = 'aarch64'
endian = 'little'
EOF
}

CROSS_IOS="$GRASA_ROOT/third_party/ios-arm64/cross-ios.meson"
CROSS_DARWIN="$GRASA_ROOT/third_party/ios-arm64/cross-darwin.meson"
gen_cross "$CROSS_IOS" ios
gen_cross "$CROSS_DARWIN" darwin

# ---------------------------------------------------------------- descargas
download() { # url
    local url="$1" fname="$(basename "$1")"
    if [ ! -f "$SRC/$fname" ]; then
        echo "[fetch] $fname"
        curl -sSL --retry 3 -o "$SRC/$fname" "$url" || { echo "[FAIL] download $url"; exit 1; }
    fi
}

extract() { # tarball dir-name
    local tb="$1" dir="$2"
    if [ ! -d "$SRC/$dir" ]; then
        echo "[extract] $dir"
        tar -xf "$SRC/$tb" -C "$SRC" || { echo "[FAIL] extract $tb"; exit 1; }
    fi
}

banner "descargando fuentes"
download "$QEMU_SRC"
download "$FFI_SRC"
download "$GLIB_SRC"
download "$PIXMAN_SRC"
download "$SLIRP_SRC"
extract "qemu-10.0.12-utm.tar.xz" "qemu-10.0.12-utm"
extract "libffi-3.5.0.tar.gz" "libffi-3.5.0"
extract "glib-2.83.0.tar.xz" "glib-2.83.0"
extract "pixman-0.38.0.tar.gz" "pixman-0.38.0"
extract "libslirp-v4.9.1.tar.gz" "libslirp-v4.9.1"

if [ ! -d "$SRC/libucontext" ]; then
    echo "[fetch] libucontext"
    git clone -q "$LIBUCONTEXT_REPO" "$SRC/libucontext" || { echo "[FAIL] clone libucontext"; exit 1; }
    ( cd "$SRC/libucontext" && git checkout -q "$LIBUCONTEXT_COMMIT" ) || { echo "[FAIL] checkout libucontext"; exit 1; }
fi

banner "descargando parches"
for p in pixman-0.38.0.patch libslirp-v4.9.1.patch qemu-10.0.12-utm.patch; do
    [ -f "$PATCHDIR/$p" ] || curl -sSL --retry 3 -o "$PATCHDIR/$p" "$PATCH_BASE/$p" || { echo "[FAIL] patch $p"; exit 1; }
done

apply_patch() { # src-dir patch-file
    local dir="$1" patch="$2"
    local stamp="$SRC/$dir/.grasadroid-patched"
    [ -f "$stamp" ] && return 0
    echo "[patch] $dir <- $patch"
    ( cd "$SRC/$dir" && patch -p1 -N --no-backup-if-mismatch -r - < "$PATCHDIR/$patch" ) >/dev/null 2>&1 || true
    touch "$stamp"
}

# ---------------------------------------------------------------- builders
build_autotools() {
    local name="$1"; shift
    local dir="$SRC/$name" log="$LOGS/$name.log"
    [ -f "$LOGS/$name.done" ] && { echo "[skip] $name"; return 0; }
    banner "building $name (autotools)"
    ( cd "$dir" \
      && ./configure --host=aarch64-apple-darwin --prefix="$PREFIX" \
                     --enable-static --disable-shared "$@" \
      && make -j"$NCPU" \
      && make install ) > "$log" 2>&1 || fail "$name" "$log"
    touch "$LOGS/$name.done"
}

build_meson() {
    local name="$1" cross="$2"; shift 2
    local dir="$SRC/$name" log="$LOGS/$name.log"
    [ -f "$LOGS/$name.done" ] && { echo "[skip] $name"; return 0; }
    banner "building $name (meson)"
    rm -rf "$dir/_grasadroid_build"
    ( cd "$dir" \
      && meson setup _grasadroid_build --cross-file "$cross" --prefix="$PREFIX" \
                --buildtype=release --default-library=static "$@" \
      && meson compile -C _grasadroid_build -j "$NCPU" \
      && meson install -C _grasadroid_build ) > "$log" 2>&1 || fail "$name" "$log"
    touch "$LOGS/$name.done"
}

# ---------------------------------------------------------------- stages
[ -f "$LOGS/libffi-3.5.0.done" ] || build_autotools libffi-3.5.0

if [ ! -f "$LOGS/glib-2.83.0.done" ]; then
    build_meson glib-2.83.0 "$CROSS_IOS" \
        -Dtests=false -Dnls=disabled -Dintrospection=disabled \
        -Dselinux=disabled -Dlibmount=disabled -Ddtrace=disabled \
        -Dman-pages=disabled -Dglib_debug=disabled -Dxattr=false
fi

if [ ! -f "$LOGS/pixman-0.38.0.done" ]; then
    apply_patch pixman-0.38.0 pixman-0.38.0.patch
    build_autotools pixman-0.38.0 --disable-gtk --disable-libpng --disable-arm-iwmmxt
fi

[ -f "$LOGS/libucontext.done" ] || build_meson libucontext "$CROSS_IOS" -Dfreestanding=true

if [ ! -f "$LOGS/libslirp-v4.9.1.done" ]; then
    apply_patch libslirp-v4.9.1 libslirp-v4.9.1.patch
    build_meson libslirp-v4.9.1 "$CROSS_DARWIN"
fi

# ---------------------------------------------------------------- qemu
if [ ! -f "$LOGS/qemu.done" ]; then
    apply_patch qemu-10.0.12-utm qemu-10.0.12-utm.patch
    banner "building qemu (this is the long one)"
    qdir="$SRC/qemu-10.0.12-utm"
    rm -rf "$qdir/_grasadroid_build"; mkdir -p "$qdir/_grasadroid_build"
    ( cd "$qdir/_grasadroid_build" \
      && ../configure \
            --prefix="$PREFIX" \
            --cross-prefix="" \
            --target-list=aarch64-softmmu \
            --enable-shared-lib \
            --with-coroutine=libucontext \
            --enable-slirp \
            --disable-cocoa --disable-sdl --disable-gtk --disable-coreaudio \
            --disable-vnc --disable-spice \
            --disable-curses --disable-curl --disable-libusb --disable-usb-redir \
            --disable-tpm --disable-docs --disable-guest-agent --disable-tools \
            --disable-hvf --disable-vde --disable-brlapi --disable-libssh \
            --disable-bzip2 --disable-snappy --disable-lzo --disable-gnutls \
            --disable-png --disable-vte --disable-zstd \
            --disable-nettle --disable-gcrypt --disable-auth-pam \
            --disable-install-blobs --disable-sparse --disable-debug-info \
            --extra-cflags="$CFLAGS" --extra-ldflags="$LDFLAGS" \
      && make -j"$NCPU" ) > "$LOGS/qemu.log" 2>&1 || fail qemu "$LOGS/qemu.log"
    touch "$LOGS/qemu.done"
fi

# ---------------------------------------------------------------- stage dylib
DYLIB_SRC="$SRC/qemu-10.0.12-utm/_grasadroid_build/libqemu-aarch64-softmmu.dylib"
if [ -f "$DYLIB_SRC" ]; then
    cp "$DYLIB_SRC" "$LIBDIR/"
    echo "[stage] $LIBDIR/libqemu-aarch64-softmmu.dylib"
    ls -lh "$LIBDIR/libqemu-aarch64-softmmu.dylib"
else
    echo "[FAIL] dylib not produced"; exit 1
fi

echo
echo "QEMU iOS build OK"
